#!/usr/bin/env python3
"""Bake the capture menu's Lucide glyphs into a Rust module.

The C++ toolbar draws its icons as Lucide font glyphs. The Cairo menu on the
GTK path cannot shape text into a fill, so this script extracts the outlines
from the bundled font and writes them as path commands in font units (1000
units per em, y pointing up). Run it again only when the icons or the font
change.
"""

from pathlib import Path

from fontTools.pens.basePen import BasePen
from fontTools.pens.boundsPen import BoundsPen
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parent.parent
FONT_PATH = ROOT / "capture-overlay" / "assets" / "fonts" / "Lucide.ttf"
OUTPUT_PATH = ROOT / "src" / "overlay" / "capture_menu_icons.rs"

# Constant name, codepoint, glyph name.
GLYPHS = [
    ("CAMERA", 0xE064, "camera"),
    ("VIDEO", 0xE1A5, "video"),
    ("MONITOR", 0xE11D, "monitor"),
    ("APP_WINDOW", 0xE426, "app-window"),
    ("SCAN", 0xE257, "scan"),
    ("SCAN_TEXT", 0xE538, "scan-text"),
    ("TIMER", 0xE1E0, "timer"),
    ("MIC", 0xE118, "mic"),
    ("VOLUME_2", 0xE1AB, "volume-2"),
    ("X", 0xE1B2, "x"),
]


class OutlinePen(BasePen):
    """Collect a glyph outline, converting quadratics to exact cubics."""

    def __init__(self, glyph_set):
        super().__init__(glyph_set)
        self.segments = []

    def _moveTo(self, point):
        self.segments.append(("Move", point))

    def _lineTo(self, point):
        self.segments.append(("Line", point))

    def _curveToOne(self, control1, control2, point):
        self.segments.append(("Curve", control1, control2, point))

    def _qCurveToOne(self, control, point):
        start = self._getCurrentPoint()
        control1 = (
            start[0] + 2.0 / 3.0 * (control[0] - start[0]),
            start[1] + 2.0 / 3.0 * (control[1] - start[1]),
        )
        control2 = (
            point[0] + 2.0 / 3.0 * (control[0] - point[0]),
            point[1] + 2.0 / 3.0 * (control[1] - point[1]),
        )
        self.segments.append(("Curve", control1, control2, point))

    def _closePath(self):
        self.segments.append(("Close",))


def number(value):
    rounded = round(float(value), 2)
    # Keep "-0.00" out of the generated file.
    if rounded == 0.0:
        rounded = 0.0
    return f"{rounded:.2f}"


def segment_source(segment):
    kind = segment[0]
    if not segment[1:]:
        return "        Seg::Close,"
    points = ", ".join(number(value) for point in segment[1:] for value in point)
    return f"        Seg::{kind}({points}),"


def glyph_source(name, codepoint, glyph_name, glyph_set, cmap):
    resolved = cmap.get(codepoint)
    if resolved != glyph_name:
        raise SystemExit(
            f"0x{codepoint:04X} maps to {resolved!r}, expected {glyph_name!r}"
        )

    pen = OutlinePen(glyph_set)
    glyph_set[glyph_name].draw(pen)
    if not pen.segments or pen.segments[0][0] != "Move":
        raise SystemExit(f"{glyph_name!r} has no outline")

    bounds_pen = BoundsPen(glyph_set)
    glyph_set[glyph_name].draw(bounds_pen)
    if bounds_pen.bounds is None:
        raise SystemExit(f"{glyph_name!r} has no ink bounds")

    bounds = ", ".join(number(value) for value in bounds_pen.bounds)
    lines = [
        f"pub(super) const {name}: Glyph = Glyph {{",
        f"    bounds: ({bounds}),",
        "    segs: &[",
    ]
    lines.extend(segment_source(segment) for segment in pen.segments)
    lines.extend(["    ],", "};"])
    return "\n".join(lines)


def main():
    font = TTFont(FONT_PATH)
    cmap = font.getBestCmap()
    glyph_set = font.getGlyphSet()

    header = """\
//! Outline data for the capture menu's icons.
//!
//! Generated by `scripts/generate_capture_menu_icons.py` from the bundled
//! Lucide font (`capture-overlay/assets/fonts/Lucide.ttf`). Lucide is ISC
//! licensed; see `capture-overlay/assets/fonts/Lucide-LICENSE.txt` or
//! <https://lucide.dev>. Do not edit this file by hand.

/// One path command in font units (1000 units per em, y pointing up).
pub(super) enum Seg {
    Move(f64, f64),
    Line(f64, f64),
    Curve(f64, f64, f64, f64, f64, f64),
    Close,
}

/// A glyph outline and its exact ink bounds `(min_x, min_y, max_x, max_y)`.
pub(super) struct Glyph {
    pub bounds: (f64, f64, f64, f64),
    pub segs: &'static [Seg],
}
"""

    blocks = [
        glyph_source(name, codepoint, glyph_name, glyph_set, cmap)
        for name, codepoint, glyph_name in GLYPHS
    ]
    OUTPUT_PATH.write_text(header + "\n" + "\n\n".join(blocks) + "\n")


if __name__ == "__main__":
    main()
